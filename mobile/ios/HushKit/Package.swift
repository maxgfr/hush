// swift-tools-version: 5.10
import PackageDescription

// The engine is a Rust static library (mobile/scripts/build-ios.sh). Xcode and CI link it from
// the XCFramework; without Xcode, that script only builds the Mac library: point HUSH_FFI_DIR at it
// (mobile/ios/build/macos) to build and test HushKit on this Mac.
let localFFI = Context.environment["HUSH_FFI_DIR"]

// Clients of HushFFI must see its C module too.
let ffiFlags: [SwiftSetting] = localFFI.map {
    [.unsafeFlags(["-Xcc", "-fmodule-map-file=\($0)/module.modulemap"])]
} ?? []

// What the Rust standard library and its dependencies (rustls, the system resolver) link to.
var ffiLinks: [LinkerSetting] = [
    .linkedFramework("Security"),
    .linkedFramework("SystemConfiguration"),
    .linkedFramework("CoreFoundation"),
]
var ffiDeps: [Target.Dependency] = []
var binary: [Target] = []
if let dir = localFFI {
    ffiLinks += [.unsafeFlags(["-L\(dir)"]), .linkedLibrary("hush_ffi")]
} else {
    binary = [.binaryTarget(name: "hush_ffiFFI", path: "../build/HushFFI.xcframework")]
    ffiDeps = ["hush_ffiFFI"]
}

let package = Package(
    name: "HushKit",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [.library(name: "HushKit", targets: ["HushKit"])],
    targets: binary + [
        // The UniFFI bindings, generated by build-ios.sh.
        .target(name: "HushFFI", dependencies: ffiDeps, swiftSettings: ffiFlags, linkerSettings: ffiLinks),
        .target(name: "HushKit", dependencies: ["HushFFI"], swiftSettings: ffiFlags),
        .testTarget(name: "HushKitTests", dependencies: ["HushKit"], swiftSettings: ffiFlags),
    ]
)
